def build_prompt(segment_no, title, refs, shots, include_shen):
    lines = [character_header(include_shen), ""]
    for index, key in enumerate(refs, 1):
        lines.append(reference_line(index, key))
    lines.extend(["", f"Segment {segment_no:02d}：{title}", "", "四个镜头在同一任务链上连续推进，人物动作承接上一镜头，物体不得自行移动。", ""])
    names = ["一", "二", "三", "四"]
    for idx, item in enumerate(shots):
        lines.extend([
            f"镜头{names[idx]}｜{item['title']}",
            f"景别：{item['framing']}。",
            f"构图：{item['composition']}。",
            f"运镜手法：{item['camera']}。",
            f"画面内容：{item['content']}",
        ])
        for speaker, dialogue in item["dialogue"]:
            lines.extend([f"{speaker}：", f"“{dialogue}”"])
        lines.append("")
    lines.extend([
        "声音：保留对应环境声、设备声和动作声；人物说话时背景声压低，对白清楚。禁止字幕、水印、logo。",
        "禁止：动画、二次元、游戏CG、赛博朋克、血腥特写、人物换脸、人物换装、数字人原始服装、物体瞬移、自动施工、数量漂移、第二栋别墅、农业区出现在围墙外。",
    ])
    return "\n".join(lines) + "\n"


